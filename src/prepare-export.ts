import JSZip from 'jszip';

type File={path:string;bytes:Uint8Array};
type Occurrence={figmaNodeId:string;screen:string;screenNodeId:string};
type Entry={id:string;name:string;path:string;type:'svg'|'image';figmaNodeId:string;screen:string;screenNodeId:string;usage:string;uses:number;occurrences:Occurrence[]};
type Note={nodeId:string;name:string;reason:string};
const decoder=new TextDecoder();
export function fingerprint(bytes:Uint8Array|Uint8ClampedArray){
  let hash=2166136261;
  for(const byte of bytes){hash^=byte;hash=Math.imul(hash,16777619);}
  return `${bytes.length}:${hash>>>0}`;
}
export const samePixels=(a:Uint8ClampedArray,b:Uint8ClampedArray)=>a.length===b.length&&a.every((v,i)=>v===b[i]);

export function canonicalSvg(source:string){
  const document=new DOMParser().parseFromString(source,'image/svg+xml');
  if(document.querySelector('parsererror')||document.documentElement.localName!=='svg')throw new Error('Invalid SVG');
  if(document.querySelector('image, foreignObject, script'))throw new Error('SVG contains raster or unsupported content');
  document.querySelectorAll('metadata, title, desc').forEach(node=>node.remove());
  // Generated paint/clip IDs vary between copies. Preserve their internal references.
  const ids=new Map<string,string>();
  if(!document.querySelector('style'))document.querySelectorAll('[id]').forEach((node,index)=>ids.set(node.id,`asset_ref_${index}`));
  const normalize=(element:Element)=>{
    const attributes=Array.from(element.attributes).map(a=>({name:a.name,namespace:a.namespaceURI,value:a.value}));
    for(const a of Array.from(element.attributes))element.removeAttributeNode(a);
    attributes.sort((a,b)=>a.name.localeCompare(b.name)).forEach(a=>{
      if(['data-name','data-node-id','aria-labelledby'].includes(a.name))return;
      let value=a.value;
      if(a.name==='id')value=ids.get(value)||value;
      if((a.name==='href'||a.name==='xlink:href')&&value.startsWith('#'))value=`#${ids.get(value.slice(1))||value.slice(1)}`;
      value=value.replace(/url\(\s*['"]?#([^\s)'"]+)['"]?\s*\)/g,(_,id:string)=>`url(#${ids.get(id)||id})`);
      element.setAttributeNS(a.namespace,a.name,value);
    });
    for(const child of Array.from(element.childNodes)){
      if(child.nodeType===8)child.remove();
      else if(child.nodeType===3&&!child.textContent?.trim()&&!['text','tspan','textPath'].includes(element.localName))child.remove();
      else if(child.nodeType===1)normalize(child as Element);
    }
  };
  normalize(document.documentElement);
  return new XMLSerializer().serializeToString(document.documentElement);
}

export async function renderPixels(bytes:Uint8Array,type:'svg'|'image'){
  const blob=new Blob([new Uint8Array(bytes)],{type:type==='svg'?'image/svg+xml':'image/png'});
  const url=URL.createObjectURL(blob);
  const image=new Image();
  let timer:ReturnType<typeof setTimeout>|undefined;
  try{
    await new Promise<void>((resolve,reject)=>{
      image.onload=()=>resolve();image.onerror=()=>reject(new Error('Image could not be rendered'));
      timer=setTimeout(()=>reject(new Error('Image rendering timed out')),30000);image.src=url;
    });
    const width=Math.ceil(image.naturalWidth),height=Math.ceil(image.naturalHeight);
    if(!width||!height)throw new Error('Zero-size asset');
    if(width>16384||height>16384||width*height>32000000)throw new Error('Asset exceeds the 32-megapixel validation limit');
    const canvas=document.createElement('canvas');canvas.width=width;canvas.height=height;
    const context=canvas.getContext('2d',{willReadFrequently:true});
    if(!context)throw new Error('Canvas unavailable');
    try{
      context.drawImage(image,0,0);
      const pixels=context.getImageData(0,0,width,height).data;
      let painted=false;
      for(let i=0;i<pixels.length;i+=4){
        if(pixels[i+3])painted=true;
        else pixels[i]=pixels[i+1]=pixels[i+2]=0;
      }
      return {width,height,pixels,painted};
    }finally{canvas.width=canvas.height=0;}
  }finally{clearTimeout(timer);image.onload=image.onerror=null;URL.revokeObjectURL(url);}
}

export function dartConstants(assets:Entry[]){
  const used=new Set<string>();
  const lines=assets.map(a=>{
    let base=a.id.replace(/_([a-z0-9])/g,(_,c:string)=>c.toUpperCase());
    if(!/^[a-zA-Z]/.test(base)||/^(class|switch|default|return|static|final|const|var|new|this|super|true|false|null|abstract|void|enum|extends|with|implements|if|else|for|while|do|try|catch|throw|assert|break|continue|in|is|rethrow|case)$/.test(base))base=`asset${base.charAt(0).toUpperCase()}${base.slice(1)}`;
    let name=base,suffix=1;while(used.has(name))name=`${base}${++suffix}`;used.add(name);
    return `  static const String ${name} = '${a.path}';`;
  });
  return `// Generated by Flutter Assets Exporter.\nabstract final class AppAssets {\n${lines.join('\n')}\n}\n`;
}

export async function prepareExport(files:File[],progress:(message:string)=>void){
  const byPath=new Map(files.map(file=>[file.path,new Uint8Array(file.bytes)]));
  const read=(path:string)=>JSON.parse(decoder.decode(byPath.get(path)));
  const manifest=read('metadata/assets_manifest.json') as {version:number;screens:{name:string;figmaNodeId:string}[];assets:Entry[]};
  const notes:Note[]=read('metadata/export_report.json').skipped;
  const assets:Entry[]=[];
  const svgIndex=new Map<string,Entry>();
  const imageIndex=new Map<string,Entry[]>();
  let duplicates=manifest.assets.reduce((count,a)=>count+a.uses-1,0),empty=0;
  for(const [index,asset] of manifest.assets.entries()){
    progress(`Checking visible content and duplicates… ${index+1}/${manifest.assets.length}`);
    const bytes=byPath.get(asset.path)!;
    try{
      const canonical=asset.type==='svg'?canonicalSvg(decoder.decode(bytes)):undefined;
      const rendered=await renderPixels(bytes,asset.type);
      if(!rendered.painted){
        empty++;notes.push({nodeId:asset.figmaNodeId,name:asset.name,reason:'Fully transparent / empty output'});continue;
      }
      let duplicate=canonical!==undefined?svgIndex.get(canonical):undefined;
      const imageKey=`${rendered.width}x${rendered.height}:${fingerprint(rendered.pixels)}`;
      if(asset.type==='image'){
        // Compare full pixels to guard against hash collisions; only two decoded images stay live.
        for(const previous of imageIndex.get(imageKey)||[]){
          const other=await renderPixels(byPath.get(previous.path)!,'image');
          if(samePixels(rendered.pixels,other.pixels)){duplicate=previous;break;}
        }
      }
      if(duplicate){
        duplicate.occurrences.push(...asset.occurrences);duplicate.uses=duplicate.occurrences.length;
        duplicates++;continue;
      }
      assets.push(asset);
      if(canonical!==undefined)svgIndex.set(canonical,asset);
      else imageIndex.set(imageKey,[...(imageIndex.get(imageKey)||[]),asset]);
    }catch(error){notes.push({nodeId:asset.figmaNodeId,name:asset.name,reason:`Validation failed: ${String(error)}`});}
    // Keep the plugin responsive during a large export.
    await new Promise(resolve=>setTimeout(resolve,0));
  }
  manifest.version=2;manifest.assets=assets;
  const zip=new JSZip();
  for(const asset of assets)zip.file(asset.path,byPath.get(asset.path)!);
  for(const file of files)if(file.path.startsWith('tokens/')||file.path==='metadata/README.md')zip.file(file.path,byPath.get(file.path)!);
  const json=(path:string,value:unknown)=>zip.file(path,JSON.stringify(value,null,2));
  json('metadata/assets_manifest.json',manifest);
  json('metadata/screen_mapping.json',{screens:manifest.screens.map(screen=>({
    screen:screen.name,figmaNodeId:screen.figmaNodeId,
    assets:assets.filter(a=>a.occurrences.some(o=>o.screenNodeId===screen.figmaNodeId)).map(a=>({
      id:a.id,path:a.path,usage:a.usage,
      figmaNodeIds:a.occurrences.filter(o=>o.screenNodeId===screen.figmaNodeId).map(o=>o.figmaNodeId),
      uses:a.occurrences.filter(o=>o.screenNodeId===screen.figmaNodeId).length
    }))
  }))});
  json('metadata/export_report.json',{duplicatesRemoved:duplicates,emptyRemoved:empty,skipped:notes});
  zip.file('lib/generated/app_assets.dart',dartConstants(assets));
  return {zip,assets,duplicates,empty,notes};
}
